def create_seasonal_features_regional(weather_df):
    """
    Create seasonal features from monthly regional weather data
    Same features as national model, but calculated for each region
    """
    
    seasonal_features = []
    
    # Group by Year and Region
    for (year, region), group in weather_df.groupby(['Year', 'Region']):
        
        # Sort by month
        group = group.sort_values('Month')
        
        # Define seasons (Northern Hemisphere)
        winter_months = [12, 1, 2]  # Dec, Jan, Feb
        spring_months = [3, 4, 5]    # Mar, Apr, May
        summer_months = [6, 7, 8]    # Jun, Jul, Aug
        autumn_months = [9, 10, 11]  # Sep, Oct, Nov
        
        # Get seasonal data
        winter = group[group['Month'].isin(winter_months)]
        spring = group[group['Month'].isin(spring_months)]
        summer = group[group['Month'].isin(summer_months)]
        autumn = group[group['Month'].isin(autumn_months)]
        
        features = {
            'Year': year,
            'Region': region,
            
            # ================================================================
            # TEMPERATURE FEATURES
            # ================================================================
            
            # Seasonal max temperatures
            'Winter_Tmax': winter['Tmax'].mean(),
            'Spring_Tmax': spring['Tmax'].mean(),
            'Summer_Tmax': summer['Tmax'].mean(),
            'Autumn_Tmax': autumn['Tmax'].mean(),
            
            # Seasonal min temperatures
            'Winter_Tmin': winter['Tmin'].mean(),
            'Spring_Tmin': spring['Tmin'].mean(),
            'Summer_Tmin': summer['Tmin'].mean(),
            'Autumn_Tmin': autumn['Tmin'].mean(),
            
            # Mean temperatures
            'Spring_Temp_Mean': spring[['Tmax', 'Tmin']].mean().mean(),
            'Summer_Temp_Mean': summer[['Tmax', 'Tmin']].mean().mean(),
            
            # Critical growth periods
            'Flowering_Temp': group[group['Month'].isin([5, 6])][['Tmax', 'Tmin']].mean().mean(),
            'Grain_Filling_Temp': group[group['Month'].isin([7, 8])][['Tmax', 'Tmin']].mean().mean(),
            
            # Temperature extremes
            'Summer_Tmax_Peak': summer['Tmax'].max(),
            'Spring_Tmin_Coldest': spring['Tmin'].min(),
            
            # Temperature ranges
            'Spring_Temp_Range': spring['Tmax'].mean() - spring['Tmin'].mean(),
            'Summer_Temp_Range': summer['Tmax'].mean() - summer['Tmin'].mean(),
            
            # Growing Degree Days (GDD) - base 5°C
            'Spring_GDD': ((spring[['Tmax', 'Tmin']].mean(axis=1) - 5).clip(lower=0)).sum(),
            'Summer_GDD': ((summer[['Tmax', 'Tmin']].mean(axis=1) - 5).clip(lower=0)).sum(),
            
            # ================================================================
            # RAINFALL FEATURES
            # ================================================================
            
            # Seasonal totals
            'Winter_Rain': winter['Rainfall'].sum(),
            'Spring_Rain': spring['Rainfall'].sum(),
            'Summer_Rain': summer['Rainfall'].sum(),
            'Autumn_Rain': autumn['Rainfall'].sum(),
            
            # Critical periods
            'Planting_Rain': group[group['Month'].isin([9, 10, 11])]['Rainfall'].sum(),  # Autumn planting
            'Grain_Filling_Rain': group[group['Month'].isin([7, 8])]['Rainfall'].sum(),
            'Harvest_Rain': group[group['Month'].isin([8, 9])]['Rainfall'].sum(),
            
            # Annual total
            'Annual_Rain': group['Rainfall'].sum(),
            
            # Deviation from optimal (assuming ~500mm for growing season)
            'Rain_Deviation_from_Optimal': abs(spring['Rainfall'].sum() + summer['Rainfall'].sum() - 500),
            
            # Squared terms for non-linear effects
            'Spring_Rain_Squared': spring['Rainfall'].sum() ** 2,
            'Summer_Rain_Squared': summer['Rainfall'].sum() ** 2,
            
            # ================================================================
            # SUNSHINE FEATURES
            # ================================================================
            
            # Seasonal totals
            'Winter_Sun': winter['Sunshine'].sum(),
            'Spring_Sun': spring['Sunshine'].sum(),
            'Summer_Sun': summer['Sunshine'].sum(),
            'Autumn_Sun': autumn['Sunshine'].sum(),
            
            # Critical periods
            'Grain_Filling_Sun': group[group['Month'].isin([7, 8])]['Sunshine'].sum(),
            'Flowering_Sun': group[group['Month'].isin([5, 6])]['Sunshine'].sum(),
            
            # Sunshine efficiency
            'Summer_Sun_per_Rain': summer['Sunshine'].sum() / max(summer['Rainfall'].sum(), 1),
            
            # ================================================================
            # FROST FEATURES
            # ================================================================
            
            # Seasonal totals
            'Winter_Frost': winter['Frost'].sum(),
            'Spring_Frost': spring['Frost'].sum(),
            'Autumn_Frost': autumn['Frost'].sum(),
            'Late_Spring_Frost': group[group['Month'].isin([4, 5])]['Frost'].sum(),
            
            # ================================================================
            # INTERACTION & EXTREME FEATURES
            # ================================================================
            
            # Temperature × Rainfall interactions
            'Spring_Temp_x_Rain': spring[['Tmax', 'Tmin']].mean().mean() * spring['Rainfall'].sum(),
            'Summer_Temp_x_Rain': summer[['Tmax', 'Tmin']].mean().mean() * summer['Rainfall'].sum(),
            
            # Temperature × Sunshine
            'Summer_Temp_x_Sun': summer['Tmax'].mean() * summer['Sunshine'].sum(),
            
            # Extreme events (binary indicators)
            'Heat_Stress': int(summer['Tmax'].max() > 30),  # Heat stress threshold
            'Cold_Spring': int(spring['Tmin'].min() < 0),   # Spring frost damage
            'Extreme_Summer_Rain': int(summer['Rainfall'].sum() > 350),  # Wet summer (like 2012)
            'Drought_Spring': int(spring['Rainfall'].sum() < 150),  # Spring drought
        }
        
        seasonal_features.append(features)
    
    return pd.DataFrame(seasonal_features)

