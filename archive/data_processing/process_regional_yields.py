all_data = []

crops_dict = {
    'Wheat': wheat_data,
    'Barley': barley_data,
    'Oats': oats_data,
    'Oilseed_Rape': oilseed_data
}

for crop_name, crop_data in crops_dict.items():
    for region in regions:
        for i, year in enumerate(years):
            row = {
                'Year': year,
                'Region': region,
                'Crop': crop_name,
                'Area_hectares': crop_data['Area'][region][i],
                'Yield_t_per_ha': crop_data['Yield'][region][i]
            }
            all_data.append(row)

