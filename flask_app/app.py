# Pre-load models, scalers, and metadata
_models = {}
_scalers = {}
_meta = {}
_models_dir = os.path.join(os.path.dirname(__file__), 'models')
for crop_name in CROPS:
    model_file = os.path.join(_models_dir, f'{crop_name.lower()}_model.pkl')
    scaler_file = os.path.join(_models_dir, f'{crop_name.lower()}_scaler.pkl')
    meta_file = os.path.join(_models_dir, f'{crop_name.lower()}_meta.pkl')
    if os.path.exists(model_file) and os.path.exists(scaler_file):
        _models[crop_name] = joblib.load(model_file)
        _scalers[crop_name] = joblib.load(scaler_file)
    if os.path.exists(meta_file):
        _meta[crop_name] = joblib.load(meta_file)


